import Foundation

public struct BulkCommand: Sendable, Equatable {
    public static let headerLength = 8

    public let name: String
    public let bytes: [UInt8]

    public init(_ name: String, _ bytes: [UInt8]) {
        self.name = name
        self.bytes = bytes
    }

    public var commandID: UInt8 { bytes[0] }
    public var subcommand: UInt8 { bytes[3] }
    public var declaredPayloadLength: Int { Int(bytes[5]) }
    public var isWellFormed: Bool {
        bytes.count >= Self.headerLength
            && bytes[1] == 0x91
            && bytes.count == Self.headerLength + declaredPayloadLength
    }

    public static func make(command: UInt8, subcommand: UInt8, payload: [UInt8], name: String) -> BulkCommand {
        precondition(payload.count <= 0xFF)
        let header: [UInt8] = [command, 0x91, 0x00, subcommand, 0x00, UInt8(payload.count), 0x00, 0x00]
        return BulkCommand(name, header + payload)
    }
}

public enum WakeUpSequence {
    public enum Variant: String, CaseIterable, Sendable {
        case sdl
        case extended
    }

    public enum InputReportFormat: UInt8, Sendable, CaseIterable {
        case vendor = 0x05
        case hid = 0x09
    }

    public static let playerLEDPatterns: [UInt8] = [0x1, 0x3, 0x7, 0xF, 0x9, 0x5, 0xD, 0x6]

    public static let reset = BulkCommand("reset (re-enumerate)", [0x03, 0x91, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00])

    public static func setInputReportFormat(_ format: InputReportFormat) -> BulkCommand {
        .make(command: 0x03, subcommand: 0x0A, payload: [format.rawValue, 0, 0, 0],
              name: "set input report format 0x\(String(format.rawValue, radix: 16))")
    }

    public static func playerLED(player: Int) -> BulkCommand {
        let pattern = playerLEDPatterns[max(0, player - 1) % playerLEDPatterns.count]
        return .make(command: 0x09, subcommand: 0x07,
                     payload: [pattern, 0, 0, 0, 0, 0, 0, 0],
                     name: "set player LED \(player)")
    }

    public static func flashRead(address: UInt32) -> BulkCommand {
        var payload = [UInt8](repeating: 0, count: 8)
        payload[4] = UInt8(address & 0xFF)
        payload[5] = UInt8((address >> 8) & 0xFF)
        payload[6] = UInt8((address >> 16) & 0xFF)
        payload[7] = UInt8((address >> 24) & 0xFF)
        return .make(command: 0x02, subcommand: 0x01, payload: payload,
                     name: String(format: "flash read 0x%06X", address))
    }

